def _clean_text(text: str) -> str:
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"[^\w\s가-힣]", " ", text)
    return text.strip()


def train(output_path: Path) -> None:
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import Pipeline
    from sklearn.preprocessing import LabelEncoder
    from sklearn.model_selection import cross_val_score
    import numpy as np
    import joblib

    texts = [_clean_text(t) for t, _ in SEED_DATA]
    raw_labels = [lbl for _, lbl in SEED_DATA]

    le = LabelEncoder()
    labels = le.fit_transform(raw_labels)

    print(f"클래스: {list(le.classes_)}")
    print(f"클래스별 샘플 수: { {c: raw_labels.count(c) for c in le.classes_} }")

    pipe = Pipeline([
        ("tfidf", TfidfVectorizer(
            analyzer="char_wb",
            ngram_range=(2, 4),
            max_features=50_000,
            sublinear_tf=True,
            min_df=1,
        )),
        ("clf", LogisticRegression(
            C=5.0,
            solver="saga",
            max_iter=1000,
            multi_class="multinomial",
            n_jobs=-1,
            random_state=42,
        )),
    ])

    # 교차 검증
    scores = cross_val_score(pipe, texts, labels, cv=5, scoring="accuracy")
    print(f"5-fold CV 정확도: {scores.mean():.3f} ± {scores.std():.3f}")

    # 전체 데이터로 최종 훈련
    pipe.fit(texts, labels)

    # 훈련 데이터 accuracy
    train_acc = (pipe.predict(texts) == labels).mean()
    print(f"훈련 정확도: {train_acc:.3f}")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump({"pipeline": pipe, "label_encoder": le}, output_path)
    print(f"\n모델 저장: {output_path}")

    # 검증 테스트
    test_cases = [
        ("우리 동네 가로등이 꺼져 있습니다", "민원"),
        ("버스 노선을 늘려주면 좋겠습니다", "제안"),
        ("최저임금법 개정을 청원합니다", "청원"),
        ("교통 안전을 위한 도로교통법 개정이 필요합니다", "청원"),
        ("공공 자전거를 더 많이 설치해야 합니다", "제안"),
        ("쓰레기 수거가 안 됩니다", "민원"),
    ]
    print("\n[분류 테스트]")
    for text, expected in test_cases:
        cleaned = _clean_text(text)
        pred_idx = pipe.predict([cleaned])[0]
        pred_label = le.inverse_transform([pred_idx])[0]
        proba = pipe.predict_proba([cleaned])[0]
        confidence = proba.max()
        status = "✓" if pred_label == expected else "✗"
        print(f"{status} [{expected}→{pred_label}] ({confidence:.2f}) {text}")


